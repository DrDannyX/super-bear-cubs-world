const cache = new Map();

function glyph(ch, color) {
  const key = ch + color;
  let c = cache.get(key);
  if (c) return c;
  c = makeCanvas(5, 7);
  const src = GLYPHS[ch];
  if (src) {
    const g = c.getContext('2d');
    g.fillStyle = color;
    src.split('|').forEach((row, y) => {
      for (let x = 0; x < 5; x++) if (row[x] === '#') g.fillRect(x, y, 1, 1);
    });
  }
  cache.set(key, c);
  return c;
}

export function textWidth(text, scale = 1) {
  return text.length * 6 * scale - scale;
}

// color may be a string or a function (index) => colour for rainbow text.
export function drawText(ctx, text, x, y, opts = {}) {
  const { color = '#fff', scale = 1, shadow = '#000', align = 'left' } = opts;
  text = String(text).toUpperCase();
  if (align === 'center') x -= Math.floor(textWidth(text, scale) / 2);
  else if (align === 'right') x -= textWidth(text, scale);
  x = Math.round(x);
  y = Math.round(y);
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (ch !== ' ') {
      const cx = x + i * 6 * scale;
      if (shadow) ctx.drawImage(glyph(ch, shadow), cx + scale, y + scale, 5 * scale, 7 * scale);
      const col = typeof color === 'function' ? color(i) : color;
      ctx.drawImage(glyph(ch, col), cx, y, 5 * scale, 7 * scale);
    }
  }
}
